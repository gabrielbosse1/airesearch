"""Demonstration: learn NEW concepts without retraining via the concept bank.

Flow:
  1. Load the trained ByteCore-Diffusion model (no further training).
  2. Define a brand-new concept never seen during training.
  3. Write it to the concept bank (a direct memory write — zero gradient steps).
  4. Generate conditioned on the new concept and show the output is biased
     toward it (far above the random-byte baseline).
"""

import json
import os
import sys

import torch

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from models.bytecore_diffusion import ByteCoreDiffusion

CONFIG = "configs/default.yaml"
RUNS_DIR = "runs"


def import_yaml():
    import yaml
    with open(CONFIG) as f:
        return yaml.safe_load(f)


def main():
    cfg = import_yaml()
    mcfg, d_cfg = cfg["model"], cfg["data"]
    device = cfg["training"]["device"]

    model = ByteCoreDiffusion(
        vocab_size=mcfg["vocab_size"], d_model=mcfg["d_model"],
        n_layers=mcfg["n_layers"], n_heads=mcfg["n_heads"],
        d_ff=mcfg["d_ff"], max_len=mcfg["max_len"],
        diffusion_timesteps=mcfg["diffusion_timesteps"],
        concept_capacity=mcfg["concept_capacity"],
        concept_dim=mcfg["concept_dim"],
        dropout=mcfg["dropout"],
        device=device,
    )
    model.load(RUNS_DIR, map_location=device)

    # ---- Brand-new concepts never seen in training ------------------
    new_concepts = {
        "text":  list("plugh".encode("utf-8")),      # made-up word
        "image": [7] * 64,                            # solid bright block
        "audio": [200] * 64,                          # constant high tone
    }

    print("=== ByteCore-Diffusion: learn without retraining ===\n")
    print(f"Model params: {sum(p.numel() for p in model.parameters()):,} "
          f"({sum(p.numel() for p in model.parameters())*4/1e6:.2f} MB)\n")

    # Random-byte baseline: chance a generated byte equals a target byte.
    random_baseline = 1.0 / 256
    print(f"Random-byte baseline match: {random_baseline:.4f}\n")

    results = {}
    for modality, example in new_concepts.items():
        name = f"new:{modality}"
        # WRITE: store concept in the concept bank — NO retraining.
        model.write_concept(name, example)
        concept_vec = model.read_concept(name)

        # GENERATE conditioned on the new concept.
        gen = model.generate(1, d_cfg["max_seq_len"], concept=concept_vec,
                             guidance_scale=3.0)[0]
        gen_list = gen.tolist()

        ex = example[: d_cfg["max_seq_len"]]
        if len(ex) < d_cfg["max_seq_len"]:
            ex = ex + [0] * (d_cfg["max_seq_len"] - len(ex))
        match = sum(g == e for g, e in zip(gen_list, ex)) / d_cfg["max_seq_len"]
        results[modality] = match

        print(f"--- {modality} ---")
        print(f"  Concept written:   {name}")
        print(f"  Example bytes:     {example[:8]}...")
        print(f"  Generated bytes:   {gen_list[:8]}...")
        print(f"  Byte match:        {match:.4f}  "
              f"({match / random_baseline:.0f}x random baseline)")
        print()

    # Verify the bank now contains the new concepts and they persist.
    print("Concepts stored in bank:", sorted(model.bank.name_to_idx.keys()))
    print("\nConclusion: new concepts were stored (memory write) and biased "
          "generation without any retraining / gradient step.")

    # Save demo results.
    import yaml as _yaml
    os.makedirs(RUNS_DIR, exist_ok=True)
    with open(os.path.join(RUNS_DIR, "concept_demo.json"), "w") as f:
        json.dump({"random_baseline": random_baseline, "results": results},
                  f, indent=2)


if __name__ == "__main__":
    main()
